    private void OKMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_OKMouseClicked
        Coelhos M = new Coelhos();
        Date dataNasc = null;
        char sexo = ' ';
        DateFormat dtOutput = new SimpleDateFormat("dd/MM/yyyy");
        M.setID_coelho(id);
        if (N.getText().equals("")) {
            JOptionPane.showMessageDialog(rootPane, "O Campo nome não pode estar vazio");
        } else {

            M.setNome(N.getText());
            M.setRaca(ESP.getText());
            if (RBF.isSelected() == true) {
                sexo = 'F';
            }
            if (RBM.isSelected() == true) {
                sexo = 'M';
            }
            M.setSexo(sexo);
            if (NASC.getText().equals("")) {
                dataNasc = null;
            } else {
                try {
                    dataNasc = dtOutput.parse(NASC.getText());
                } catch (ParseException ex) {
                    System.out.println("Erro na conversão da data");
                }
            }
            M.setData_nasc(dataNasc);
            try {
                float peso = Float.parseFloat(PES.getText());
                M.setPeso(peso);
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(rootPane, "Formato inválido: " + PES.getText());
            }

            M.setCor(COR.getText());

            CoelhosDAO PDAO = new CoelhosDAO();
            PDAO.atualizar(M);
            JOptionPane.showMessageDialog(rootPane, "Atualização efetuada com sucesso!!");
            dispose();
        }
    }//GEN-LAST:event_OKMouseClicked

