    public static void carregaCombo() {
        COMBO.removeAllItems();
        CoelhosDAO MDAO = new CoelhosDAO();
        coelho = MDAO.listar();
        for (int i = 0; i < coelho.size(); i++) {
            COMBO.addItem(coelho.get(i).getNome());
        }
    }

    public void carrega() {
        CoelhosDAO MDAO = new CoelhosDAO();
        M = MDAO.procurar(id);
        N.setText(M.getNome());
        ESP.setText(M.getRaca());

        // Clear previous selections
        RBF.setSelected(false);
        RBM.setSelected(false);

        // Set the correct selection based on the value from M
        if (M.getSexo() == 'F') {
            RBF.setSelected(true);
        } else if (M.getSexo() == 'M') {
            RBM.setSelected(true);
        }

        if (M.getData_nasc() == null) {
            NASC.setText("");
        } else {
            Date dn = M.getData_nasc();
            SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");
            NASC.setText(sdf.format(dn));
        }

        PES.setText(String.format("%.2f", M.getPeso()));
        COR.setText(M.getCor());
    }

