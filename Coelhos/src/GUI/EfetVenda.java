    public static void carregaComboProprietarios() {
            CB_prop.removeAllItems();
            ProprietariosDAO PDAO = new ProprietariosDAO();
            prop = PDAO.listar();

            for (int i = 0; i < prop.size(); i++) {
            CB_prop.addItem(prop.get(i).getNome_prop());

        }
    }
    
