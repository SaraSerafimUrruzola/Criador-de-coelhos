    private void BT_confirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BT_confirmarActionPerformed
        int mes = 0;    
        VendasDAO pdao = new VendasDAO();
            Vendas C = new Vendas();
            Calendar date = DC.getSelectedDate();
            
            C.setID_coelho(idmed);
            C.setID_comprador(idpac);
            mes = date.get(Calendar.MONTH) + 1;
            String datas = (date.get(Calendar.DAY_OF_MONTH) + "/" + mes + "/" + date.get(Calendar.YEAR));
            DateFormat dtOutput = new SimpleDateFormat("dd/MM/yyyy");
        try {
            Date data = dtOutput.parse(datas);
            C.setData_venda(data);
        } catch (ParseException ex) {
            Logger.getLogger(EfetVenda.class.getName()).log(Level.SEVERE, null, ex);
        }
        float preco = Float.parseFloat(TF_hora.getText());
        C.setPreco(preco);
            
        pdao.inserir(C);
        dispose();  
    }//GEN-LAST:event_BT_confirmarActionPerformed

