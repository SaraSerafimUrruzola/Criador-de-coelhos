    private void okMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_okMouseClicked
        Coelhos M = new Coelhos();
        Date dataNasc = null;
        char sexo = ' ';
        DateFormat dtOutput = new SimpleDateFormat("dd/MM/yyyy");
        M.setID_coelho(id);
        if (nome.getText().equals("")) {
            JOptionPane.showMessageDialog(rootPane, "O Campo nome não pode estar vazio");
        } else {
            M.setNome(nome.getText());
            M.setRaca(especialidade.getText());
            if (RBF.isSelected() == true) {
                sexo = 'F';
            }
            if (RBM.isSelected() == true) {
                sexo = 'M';
            }
            M.setSexo(sexo);
            if (dataMed.getText().equals("")) {
                dataNasc = null;
            } else {
                try {
                    dataNasc = dtOutput.parse(dataMed.getText());
                } catch (ParseException ex) {
                    System.out.println("Erro na conversão da data");
                }
            }
            M.setData_nasc(dataNasc);
            M.setCor(telefone.getText());
            try {
                float ph = Float.parseFloat(peso.getText());
                M.setPeso(ph);
            } catch (NumberFormatException e) {
                System.out.println("Invalid input: " + peso.getText() + " cannot be converted to a float.");
                // Optionally show a dialog to the user
                JOptionPane.showMessageDialog(null, "Invalid input. Please enter a valid number for peso.", "Input Error", JOptionPane.ERROR_MESSAGE);
            }

            CoelhosDAO MDAO = new CoelhosDAO();
            int confirmar = JOptionPane.showConfirmDialog(null, "Confirmar", "Vocẽ tem certeza", JOptionPane.OK_CANCEL_OPTION);
            if (confirmar == 0) {
                MDAO.excluir(M);
                JOptionPane.showMessageDialog(rootPane, "Exclusão efetuada");
                dispose();
            } else {

            }
        }
    }//GEN-LAST:event_okMouseClicked

