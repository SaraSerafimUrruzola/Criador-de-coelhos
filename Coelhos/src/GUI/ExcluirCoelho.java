    public static void carregaCombo() {
        CB_nome.removeAllItems();
        CoelhosDAO MDAO = new CoelhosDAO();
        medico = MDAO.listar();
        for (int i = 0; i < medico.size(); i++) {
            CB_nome.addItem(medico.get(i).getNome());
        }
    }

    public void carregar() {
        CoelhosDAO PDAO = new CoelhosDAO();
        M = PDAO.procurar(id);
        nome.setText(M.getNome());
        especialidade.setText(M.getRaca());
        if (RBF.isSelected() && RBM.isSelected()) {
            RBM.setSelected(false);
            RBF.setSelected(false);
        }
        if (M.getSexo() == 'F') {
            RBF.setSelected(true);
        }
        if (M.getSexo() == 'M') {
            RBM.setSelected(true);
        }

        if (M.getData_nasc() == null) {
            dataMed.setText("");
        } else {
            Date dn = null;
            String aux = "";
            SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");

            dn = M.getData_nasc();
            aux = sdf.format(dn);

            dataMed.setText(aux);
        }
        telefone.setText(M.getCor());
        peso.setText (String.valueOf(M.getPeso()));
    }


