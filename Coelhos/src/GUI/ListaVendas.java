    public static void carregaCombo() {
        ComboVendas.removeAllItems();
        VendasDAO MDAO = new VendasDAO();
        vendas = MDAO.listar();
        
        for (int i = 0; i < vendas.size(); i++) {
            ComboVendas.addItem(String.valueOf(vendas.get(i).getID_venda()));

        }
    }
