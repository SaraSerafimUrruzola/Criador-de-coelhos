 public void carregaConsultas(){
             
        Lista.removeAll();
        if (posicao != -1) {
            
            try {
                VendasCCDAO CDAO = new VendasCCDAO();
                Aux = CDAO.listarv(codigo);
            } catch (Exception ex) {
                System.out.println("problema");
            }
            Valores.clear();
            for (int i = 0; i < Aux.size(); i++) {
                Valores.addElement(Aux.get(i).getID_coelho()+"--"+Aux.get(i).getID_comprador()+"--"+Aux.get(i).getData_venda()+"--"+Aux.get(i).getPreco());
            }
            Lista.setModel(Valores);
        }

    }
    
 
 
